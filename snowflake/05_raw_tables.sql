-- Create raw birth records table

CREATE TABLE IF NOT EXISTS TSE_DB.RAW.NACIMIENTOS (
    CITA_NACIMIENTO VARCHAR(12),
    CEDULA_PROGENITOR_1 VARCHAR(9),
    CEDULA_PROGENITOR_2 VARCHAR(9),
    CODIGO_HOSPITAL VARCHAR(3),
    HORA_SUCESO VARCHAR(4),
    FECHA_SUCESO VARCHAR(8),
    RELLENO_1 VARCHAR(1),
    RELLENO_2 VARCHAR(2),
    NACIONALIDAD VARCHAR(1),
    MARCA_DEFUNCION VARCHAR(1),
    PAIS_PROGENITOR_1 VARCHAR(3),
    PAIS_PROGENITOR_2 VARCHAR(3),
    INDICADOR_ADVERTENCIA VARCHAR(1),
    PRIMER_APELLIDO VARCHAR(26),
    SEGUNDO_APELLIDO VARCHAR(26),
    NOMBRE VARCHAR(50),
    NOMBRE_PROGENITOR_1 VARCHAR(29),
    NOMBRE_PROGENITOR_2 VARCHAR(29),
    LUGAR_NACIMIENTO VARCHAR(29),
    TIPO_MOVIMIENTO VARCHAR(1),
    FECHA_MARGINAL VARCHAR(8),
    HORA_MARGINAL VARCHAR(6),
    FECHA_NATURALIZACION VARCHAR(8),
    INDICADOR_EXTENSION VARCHAR(1),
    PROVINCIA_CANTON_PROCEDENCIA VARCHAR(3),
    FECHA_APLICACION VARCHAR(8)
)
COMMENT = 'informacion Raw maestro nacimientos TSE';